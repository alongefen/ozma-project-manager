import {randomBytes,randomUUID} from 'node:crypto';
import {beforeAll,describe,expect,it,vi} from 'vitest';
import type {Platform,RequestContext,Result} from '../../../src/types/contracts';
vi.mock('server-only',()=>({}));
import {createUsersApi} from '../../../src/features/users/logic';
import {createAuthAdmin} from '../../../src/lib/auth/admin';
import {rpc,fetchAll} from '../../../src/lib/db/rpc';
import {permissions} from '../../../src/lib/permissions';
import {format} from '../../../src/lib/format';
import {cloudClients,cloudOwner,context} from '../../auth/support/cloud';
import {project} from '../../db/support/cloud';
const platform={rpc,fetchAll,permissions,format,authAdmin:createAuthAdmin({admin:()=>cloudClients().admin})} as Platform;
const api=createUsersApi(platform);
let owner:RequestContext;
function value<T>(result:Result<T>):T {
  if(!result.ok) throw new Error(`בדיקת UsersApi נכשלה: ${result.error.code}`);
  return result.value;
}
beforeAll(async()=>{owner=await cloudOwner();});
describe.sequential('UsersApi integration using approved Cloud development project',()=>{
  it('creates and retries one managed profile, edits its name and invalidates old sessions on reset/deactivation',async()=>{
    const input={requestId:randomUUID(),email:`p141-${randomUUID()}@example.invalid`,fullName:'עובד בדוי P141',password:randomBytes(32).toString('base64url')};
    const created=value(await api.createUser(owner,input));
    expect(value(await api.createUser(owner,input)).id).toBe(created.id);
    const details=value(await api.getUser(owner,{id:created.id}));
    expect(details.assignments).toEqual([]);
    expect(value(await api.listUsers(owner,{search:input.email})).map(x=>x.id)).toEqual([created.id]);
    const db=cloudClients().publicClient();
    expect((await db.auth.signInWithPassword({email:input.email,password:input.password})).error?.code).toBeUndefined();
    const member=await context(db);
    expect(await api.createUser(member,{...input,requestId:randomUUID()})).toMatchObject({ok:false,error:{code:'FORBIDDEN'}});
    expect(await api.resetPassword(member,{id:created.id,password:randomBytes(32).toString('base64url')})).toMatchObject({ok:false,error:{code:'FORBIDDEN'}});
    const saved=value(await api.updateUser(owner,{id:created.id,expectedRevision:details.revision,fullName:'שם מתוקן בדוי',email:input.email}));
    expect(value(await api.getUser(owner,{id:created.id})).fullName).toBe('שם מתוקן בדוי');
    expect(await api.updateUser(owner,{id:created.id,expectedRevision:details.revision,fullName:'ישן',email:input.email})).toMatchObject({ok:false,error:{code:'CONFLICT'}});
    const replacement=randomBytes(32).toString('base64url');
    value(await api.resetPassword(owner,{id:created.id,password:replacement}));
    expect(await api.listUsers(member,{})).toMatchObject({ok:false,error:{code:'UNAUTHENTICATED'}});
    expect((await db.auth.signInWithPassword({email:input.email,password:replacement})).error?.code).toBeUndefined();
    const refreshed=await context(db);
    const latest=value(await api.getUser(owner,{id:created.id}));
    const disabled=value(await api.setUserActive(owner,{id:created.id,expectedRevision:latest.revision,active:false}));
    expect(await api.getUser(refreshed,{id:created.id})).toMatchObject({ok:false,error:{code:'UNAUTHENTICATED'}});
    value(await api.setUserActive(owner,{id:created.id,expectedRevision:disabled.revision,active:true}));
    expect(await api.getUser(refreshed,{id:created.id})).toMatchObject({ok:false,error:{code:'UNAUTHENTICATED'}});
    expect(saved.revision).toBeGreaterThan(details.revision);
  });
  it('keeps role and finance scoped to each project, checks revisions, and removes only the selected membership',async()=>{
    const input={requestId:randomUUID(),email:`p141-roles-${randomUUID()}@example.invalid`,fullName:'בדיקת שיוכים P141',password:randomBytes(32).toString('base64url')};
    const user=value(await api.createUser(owner,input));
    const first=await project(owner.db,'P141-A');const second=await project(owner.db,'P141-B');
    let assignment=value(await api.setMembership(owner,{userId:user.id,projectId:first.id,role:'manager',expectedRevision:null}));
    expect(assignment.financeAccess).toBe(false);
    value(await api.setMembership(owner,{userId:user.id,projectId:second.id,role:'worker',expectedRevision:null}));
    const db=cloudClients().publicClient();
    expect((await db.auth.signInWithPassword({email:input.email,password:input.password})).error?.code).toBeUndefined();
    const member=await context(db);
    expect(value(await permissions.forProject(member,{projectId:first.id}))).toMatchObject({editDetails:true,viewFinance:false});
    expect(value(await permissions.forProject(member,{projectId:second.id}))).toMatchObject({editDetails:false,viewFinance:false});
    expect(await api.setMembership(member,{userId:user.id,projectId:second.id,role:'manager',expectedRevision:1})).toMatchObject({ok:false,error:{code:'FORBIDDEN'}});
    const finance=value(await api.setFinanceAccess(owner,{userId:user.id,projectId:first.id,enabled:true,expectedRevision:assignment.revision}));
    expect(value(await permissions.forProject(member,{projectId:first.id})).viewFinance).toBe(true);
    expect(await api.setFinanceAccess(owner,{userId:user.id,projectId:first.id,enabled:false,expectedRevision:assignment.revision})).toMatchObject({ok:false,error:{code:'CONFLICT'}});
    assignment=value(await api.setMembership(owner,{userId:user.id,projectId:first.id,role:'worker',expectedRevision:finance.revision}));
    expect(assignment.financeAccess).toBe(false);
    expect(value(await permissions.forProject(member,{projectId:first.id})).viewFinance).toBe(false);
    assignment=value(await api.setMembership(owner,{userId:user.id,projectId:first.id,role:'manager',expectedRevision:assignment.revision}));
    expect(assignment.financeAccess).toBe(false);
    expect(value(await api.listProjectMembers(owner,{projectId:first.id}))).toContainEqual(expect.objectContaining({userId:user.id,role:'manager',financeAccess:false}));
    value(await api.removeMembership(owner,{userId:user.id,projectId:first.id,expectedRevision:assignment.revision}));
    expect(await permissions.forProject(member,{projectId:first.id})).toMatchObject({ok:false,error:{code:'NOT_FOUND'}});
    expect(value(await permissions.forProject(member,{projectId:second.id})).view).toBe(true);
    expect(value(await api.getUser(owner,{id:user.id})).assignments.map(x=>x.projectId)).toEqual([second.id]);
  });
});
